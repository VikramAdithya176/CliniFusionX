"""
Gated Fusion Fine-Tuning Script
===================================================
This script fine-tunes the CliniFusionNet (which wraps the Swin backbone
and GatedFusion layer) on NIH ChestX-ray14 with synthetic clinical symptoms.

Requirements:
- nih_with_symptoms.csv (generated by generate_synthetic_symptoms.py)
- images/ folder with the X-ray images
- best_swin_chestxray14.pth (your existing pretrained weights)
"""

import os
import torch
import torch.nn as nn
from torch.utils.data import Dataset, DataLoader
from torchvision import transforms
from PIL import Image
import pandas as pd
from tqdm import tqdm
import json

# Import your existing models
from model import load_model, create_model
from gated_fusion import CliniFusionNet

class MultimodalChestXrayDataset(Dataset):
    def __init__(self, csv_file, img_dir, symptom_columns, label_columns, transform=None):
        self.df = pd.read_csv(csv_file)
        self.img_dir = img_dir
        self.symptom_columns = symptom_columns
        self.label_columns = label_columns
        self.transform = transform
        
    def __len__(self):
        return len(self.df)
        
    def __getitem__(self, idx):
        row = self.df.iloc[idx]
        
        # 1. Load Image
        img_name = row['Image Index']
        img_path = os.path.join(self.img_dir, img_name)
        image = Image.open(img_path).convert('RGB')
        
        if self.transform:
            image = self.transform(image)
            
        # 2. Extract Symptoms (Binary Vector)
        symptoms = row[self.symptom_columns].values.astype(float)
        symptoms_tensor = torch.tensor(symptoms, dtype=torch.float32)
        
        # 3. Extract Labels (Binary Vector)
        # Assuming finding labels are one-hot encoded or pipe-separated
        lbl_str = row['Finding Labels']
        labels = []
        for c in self.label_columns:
            if c in lbl_str:
                labels.append(1.0)
            else:
                labels.append(0.0)
                
        labels_tensor = torch.tensor(labels, dtype=torch.float32)
        
        return image, symptoms_tensor, labels_tensor


def main():
    device = torch.device("cuda" if torch.cuda.is_available() else "cpu")
    print(f"Using device: {device}")
    
    # -----------------------------------------
    # 1. Load Labels & Syntax Columns
    # -----------------------------------------
    with open("labels.json", "r") as f:
        DISEASES = json.load(f)
        
    # Get the canonical symptoms we generated in the previous script
    from generate_synthetic_symptoms import ALL_CANONICAL_SYMPTOMS
    SYMPTOM_COLS = ALL_CANONICAL_SYMPTOMS
    
    # -----------------------------------------
    # 2. Build Dataset & DataLoader
    # -----------------------------------------
    transform = transforms.Compose([
        transforms.Resize((256, 256)),
        transforms.CenterCrop(224),
        transforms.ToTensor(),
        transforms.Normalize([0.485, 0.456, 0.406], [0.229, 0.224, 0.225])
    ])
    
    train_dataset = MultimodalChestXrayDataset(
        csv_file="nih_with_symptoms.csv", 
        img_dir="images/",  # UPDATE THIS with your path to images
        symptom_columns=SYMPTOM_COLS,
        label_columns=DISEASES,
        transform=transform
    )
    
    train_loader = DataLoader(train_dataset, batch_size=32, shuffle=True, num_workers=4)
    
    # -----------------------------------------
    # 3. Initialize Model Architecture
    # -----------------------------------------
    print("Loading existing Swin weight...")
    # We create the raw Swin model without loading the classification head logic
    # because we are going to extract forward_features from it.
    try:
        swin_backbone, _ = load_model("best_swin_chestxray14.pth", "config.json", device)
    except FileNotFoundError:
        print("Warning: pre-trained weights not found, starting from scratch for demo.")
        from model import create_model
        swin_backbone = create_model("swin_tiny_patch4_window7_224", num_classes=15)
        swin_backbone.to(device)

    # Freeze the Swin Backbone to train ONLY the Fusion layer
    print("Freezing Swin Backbone...")
    for param in swin_backbone.parameters():
        param.requires_grad = False
        
    print("Initializing Gated Fusion Network...")
    model = CliniFusionNet(swin_backbone, clin_dim=len(SYMPTOM_COLS), num_classes=len(DISEASES))
    model = model.to(device)
    
    # Optionally: if you want to unfreeze the backbone later after the head converges
    # you can set requires_grad = True again on stage 3 & 4.
    
    # -----------------------------------------
    # 4. Training Loop
    # -----------------------------------------
    criterion = nn.BCEWithLogitsLoss()
    # ONLY pass the unfrozen parameters (fusion mechanism + classifier) to the optimizer
    optimizer = torch.optim.Adam(
        filter(lambda p: p.requires_grad, model.parameters()), 
        lr=1e-3
    )
    
    epochs = 5
    print("Starting Training:")
    for epoch in range(epochs):
        model.train()
        running_loss = 0.0
        
        # Wrapped in tqdm for progress bar
        # NOTE: You will need to make sure images/ exists before running
        pbar = tqdm(train_loader, desc=f"Epoch {epoch+1}/{epochs}")
        for images, symptoms, labels in pbar:
            images = images.to(device)
            symptoms = symptoms.to(device)
            labels = labels.to(device)
            
            optimizer.zero_grad()
            
            # Forward pass: note we pass BOTH image and symptoms
            outputs = model(images, symptoms)
            
            loss = criterion(outputs, labels)
            loss.backward()
            optimizer.step()
            
            running_loss += loss.item()
            pbar.set_postfix({'loss': running_loss / (pbar.n + 1)})
            
        print(f"Epoch {epoch+1} loss: {running_loss / len(train_loader):.4f}")
        
    print("Training complete! Saving new weights...")
    torch.save(model.state_dict(), "best_fused_swin.pth")
    print("Saved as best_fused_swin.pth")

if __name__ == "__main__":
    main()
